// 원작(프리빅뱅 KMS) 직업 체계 — 단일 소스 (브레인·내 메랜 공유)

export const JOB_BRANCHES = ["전사", "마법사", "궁수", "도적", "해적"] as const;

// 계열별 차수(1~4차) 직업 트리
export const JOB_TREE: Record<string, Record<number, string[]>> = {
  전사: { 1: ["검사"], 2: ["파이터", "페이지", "스피어맨"], 3: ["크루세이더", "나이트", "용기사"], 4: ["히어로", "팔라딘", "다크나이트"] },
  마법사: { 1: ["매지션"], 2: ["위자드(불,독)", "위자드(썬,콜)", "클레릭"], 3: ["메이지(불,독)", "메이지(썬,콜)", "프리스트"], 4: ["아크메이지(불,독)", "아크메이지(썬,콜)", "비숍"] },
  궁수: { 1: ["아처"], 2: ["헌터", "사수"], 3: ["레인저", "저격수"], 4: ["보우마스터", "신궁"] },
  도적: { 1: ["로그"], 2: ["어쌔신", "시프"], 3: ["허밋", "시프마스터"], 4: ["나이트로드", "섀도어"] },
  해적: { 1: ["해적"], 2: ["인파이터", "건슬링거"], 3: ["버커니어", "발키리"], 4: ["바이퍼", "캡틴"] },
};

// 레벨 → 전직 차수 (2차 30 / 3차 70 / 4차 120)
export function jobTier(level: number): number {
  return level >= 120 ? 4 : level >= 70 ? 3 : level >= 30 ? 2 : 1;
}

// 해당 레벨에서 선택 가능한 세부 직업 목록
export function subJobsFor(branch: string, level: number): string[] {
  return JOB_TREE[branch]?.[jobTier(level)] ?? [];
}
