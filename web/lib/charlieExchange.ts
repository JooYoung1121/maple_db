export type RewardGroup = "common" | "rare" | "scroll";

export interface CharlieReward {
  name: string;
  itemId: number | null; // null = v62 아이템 ID 미확인 (표기 그대로)
  qty: number;
  group: RewardGroup;
  /** 어금니 실측 확률(%) — 있는 경우만 */
  measured?: number;
}

export interface CharlieMaterial {
  name: string;
  itemId: number;
  rewards: CharlieReward[];
  /** 실측 데이터 존재 여부 */
  hasMeasured?: boolean;
}

